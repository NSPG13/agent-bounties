#!/usr/bin/env python3
"""Inspect only the dedicated staging App's provider delivery evidence.

Requires the local manifest credentials, never prints tokens or private payloads.
An explicit --redeliver asks GitHub to replay one existing staging delivery; it
does not create issues/comments, install Apps, or authorize public posting.
--replay-exact verifies the original provider HMAC before posting identical bytes
and the original delivery ID to the isolated receiver. This is a direct replay,
not a new delivery generated by GitHub.
Install scripts/requirements-attest.txt in an isolated Python environment.
"""
from __future__ import annotations

import argparse
import base64
from datetime import datetime, timezone
import hashlib
import hmac
import json
from pathlib import Path
import stat
import time
import urllib.request
import urllib.error

from Crypto.Hash import SHA256
from Crypto.PublicKey import RSA
from Crypto.Signature import pkcs1_15

ORIGIN = "https://agent-bounties-posting-api-canary.onrender.com"
REPOSITORY = "NSPG13/agent-bounties-posting-canary"


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *_args, **_kwargs):
        return None


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--credentials", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    replay = p.add_mutually_exclusive_group()
    replay.add_argument("--redeliver", type=int)
    replay.add_argument("--replay-exact", type=int,
                        help="Replay identical provider-authenticated bytes directly to staging")
    args = p.parse_args()
    if stat.S_IMODE(args.credentials.stat().st_mode) & 0o077:
        p.error("Credentials must be accessible only to their owner")
    credentials = json.loads(args.credentials.read_text())
    if credentials.get("slug") != "agentizable-staging" or credentials.get("owner", {}).get("login") != "NSPG13":
        p.error("This probe is limited to NSPG13's dedicated staging App")
    b64 = lambda value: base64.urlsafe_b64encode(value).rstrip(b"=")
    unsigned = b64(b'{"alg":"RS256","typ":"JWT"}') + b"." + b64(json.dumps({
        "iat": int(time.time()) - 60, "exp": int(time.time()) + 300,
        "iss": credentials["client_id"]}, separators=(",", ":")).encode())
    token = (unsigned + b"." + b64(pkcs1_15.new(RSA.import_key(credentials["pem"])).sign(SHA256.new(unsigned)))).decode()
    http = urllib.request.build_opener(NoRedirect())

    def api(path, method="GET"):
        request = urllib.request.Request("https://api.github.com" + path, method=method,
            data=b"" if method == "POST" else None,
            headers={"Authorization": "Bearer " + token, "Accept": "application/vnd.github+json",
                     "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "agentizable-staging-evidence"})
        with http.open(request, timeout=25) as response:
            raw = response.read(2_000_001)
            if len(raw) > 2_000_000:
                raise ValueError("Oversized provider response")
            return response.status, json.loads(raw) if raw else None

    _, config = api("/app/hook/config")
    if config["url"] != ORIGIN + "/v1/github-app/webhook" or str(config["insecure_ssl"]) != "0":
        raise ValueError("App hook is not the isolated TLS-verified receiver")
    _, deliveries = api("/app/hook/deliveries?per_page=30")
    evidence = []
    replay_result = None
    for item in deliveries:
        _, detail = api("/app/hook/deliveries/" + str(item["id"]))
        if detail["url"] != config["url"]:
            raise ValueError("Delivery destination changed")
        payload = detail.get("request", {}).get("payload", {})
        repository = payload.get("repository", {}).get("full_name")
        if repository not in (None, REPOSITORY):
            raise ValueError("Unexpected repository; do not inspect production payloads")
        if item["id"] == args.redeliver:
            if detail["event"] not in {"ping", "installation", "issue_comment", "issues"}:
                raise ValueError("Unsupported staging replay event")
            try:
                status, _ = api("/app/hook/deliveries/" + str(item["id"]) + "/attempts", "POST")
                replay_result = {"method": "provider_redelivery", "http_status": status,
                                 "accepted": status == 202}
            except urllib.error.HTTPError as error:
                # A failed response is not proof a write did not happen. Preserve
                # this evidence and inspect deliveries before considering retry.
                replay_result = {"method": "provider_redelivery", "http_status": error.code,
                                 "outcome": "unknown; inspect deliveries before retry"}
        if item["id"] == args.replay_exact:
            original_headers = {k.lower(): v for k, v in detail["request"]["headers"].items()}
            raw = json.dumps(payload, separators=(",", ":"), ensure_ascii=False).encode()
            expected = "sha256=" + hmac.new(credentials["webhook_secret"].encode(), raw, hashlib.sha256).hexdigest()
            if len(raw) > 1_048_576 or not hmac.compare_digest(expected, original_headers.get("x-hub-signature-256", "")):
                raise ValueError("Cannot reconstruct exact original bytes; do not synthesize a provider replay")
            request = urllib.request.Request(config["url"], data=raw, headers={
                "Content-Type": "application/json",
                **{k: original_headers[k] for k in ("x-hub-signature-256", "x-github-event", "x-github-delivery")}})
            try:
                response = http.open(request, timeout=25)
            except urllib.error.HTTPError as error:
                response = error
            with response:
                body = response.read(4096)
                replay_result = {"method": "direct_exact_provider_bytes", "http_status": response.status,
                                 "original_hmac_verified": True, "body_sha256": hashlib.sha256(raw).hexdigest()}
                if body:
                    try:
                        result = json.loads(body)
                    except ValueError:
                        result = None
                    if isinstance(result, dict):
                        replay_result["response"] = {k: result.get(k) for k in ("accepted", "draft_created", "funding_authority")}
        response = detail.get("response", {}).get("payload")
        try:
            response = json.loads(response) if isinstance(response, str) else response
        except ValueError:
            response = None
        evidence.append({"id": str(item["id"]), **{k: detail.get(k) for k in (
            "guid", "delivered_at", "redelivery", "status_code", "event", "action")},
            "repository": repository,
            "installation_id": payload.get("installation", {}).get("id"),
            "payload_sha256": hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest(),
            "response": {k: response.get(k) for k in ("accepted", "draft_created", "funding_authority")}
                        if isinstance(response, dict) else None})
    replay_id = args.redeliver if args.redeliver is not None else args.replay_exact
    if replay_id is not None and not any(int(d["id"]) == replay_id for d in evidence):
        raise ValueError("Replay ID is not among this App's recent deliveries")
    output = {"schema": "agent-bounties/github-staging-deliveries-v1",
              "observed_at": datetime.now(timezone.utc).isoformat(), "app_id": credentials["id"],
              "app_slug": credentials["slug"], "destination": config["url"],
              "redelivery_requested": str(args.redeliver) if args.redeliver is not None else None,
              "direct_replay_requested": str(args.replay_exact) if args.replay_exact is not None else None,
              "replay_result": replay_result,
              "deliveries": evidence}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(output, indent=2) + "\n")
    print(json.dumps(output))


if __name__ == "__main__":
    main()
